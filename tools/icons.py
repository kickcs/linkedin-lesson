#!/usr/bin/env python3
"""Lucide icons → shapes in skills/linkedin-lesson/recipe/looks/<look>/kit/icons.js, the same file in every look.
Usage: tools/icons.py <lucide-static version> <name> [<name> ...]"""
import json
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path


TOKEN = re.compile(r'([A-Za-z])|([-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?)')


def split_arcs(d):
    """Lucide glues arc flags together ("0022 17"); the rough.js parser cannot read that: write each number separately."""
    out, cmd, i = [], '', 0
    pos = 0
    while pos < len(d):
        if d[pos] in ' ,\t\n\r':
            pos += 1
            continue
        m = TOKEN.match(d, pos)
        if not m:
            raise SystemExit(f'cannot parse path: {d[pos:pos + 20]!r}')
        if m.group(1):
            cmd, i = m.group(1), 0
            out.append(cmd)
            pos = m.end()
            continue
        if cmd and cmd in 'aA' and i % 7 in (3, 4):
            if d[pos] not in '01':
                raise SystemExit(f'arc flag is not 0/1: {d[pos:pos + 20]!r}')
            out.append(d[pos])
            pos += 1
        else:
            out.append(m.group(2))
            pos = m.end()
        i += 1
    return re.sub(r'(?<=[A-Za-z]) ', '', ' '.join(out))


def shapes(svg):
    root = ET.fromstring(re.sub(r'<!--.*?-->', '', svg, flags=re.S))
    out = []
    for e in root:
        t, a = e.tag.split('}')[-1], e.attrib
        f = lambda k, d=None: float(a.get(k, d))
        if t == 'path': out.append(['p', split_arcs(a['d'])])
        elif t == 'rect': out.append(['r', f('x', 0), f('y', 0), f('width'), f('height')])
        elif t == 'circle': out.append(['c', f('cx'), f('cy'), f('r')])
        elif t == 'ellipse': out.append(['e', f('cx'), f('cy'), f('rx'), f('ry')])
        elif t == 'line': out.append(['l', f('x1'), f('y1'), f('x2'), f('y2')])
        elif t == 'polyline': out.append(['pl', a['points']])
        elif t == 'polygon': out.append(['pg', a['points']])
        else: raise SystemExit(f'unknown shape: {t}')
    return out


def main():
    ver, names = sys.argv[1], sorted(set(sys.argv[2:]))
    icons = {}
    for n in names:
        url = f'https://unpkg.com/lucide-static@{ver}/icons/{n}.svg'
        with urllib.request.urlopen(url) as r:
            icons[n] = shapes(r.read().decode())
    looks = Path(__file__).resolve().parent.parent / 'skills' / 'linkedin-lesson' / 'recipe' / 'looks'
    head = f'// Lucide {ver} (ISC, https://lucide.dev): icon shapes for the looks, generated by tools/icons.py\n'
    for out in sorted(looks.glob('*/kit/icons.js')):
        out.write_text(head + 'var ICONS = ' + json.dumps(icons, separators=(',', ':')) + ';\n')
        print(f'{len(icons)} icons → {out}')


main()
